// Build the per-request user prompt. Daily readings get today's lucky
// color; monthly readings drop it (a single day's color is irrelevant
// across a whole month) and ask for a phased month overview instead.
function buildUserPrompt(d = {}) {
  const isDaily = d.type === 'daily';
  const lines = [
    'ข้อมูลผู้ถาม:',
    `- วันเกิด: ${d.birthDate}${d.birthDayName ? ` (เกิดวัน${d.birthDayName})` : ''}`,
    `- สีมงคลประจำวันเกิด: ${d.birthDayColor || '-'}${d.birthDayColorMeaning ? ` (${d.birthDayColorMeaning})` : ''}`,
    `- ราศี: ${d.zodiac}`,
    `- นิสัยประจำราศี: ${d.zodiacTraits || '-'}`,
    `- ปีนักษัตร: ${d.chineseZodiac || '-'}`,
    `- เลขชะตา (คำนวณมาแล้ว ใช้ตามนี้): ${d.lifePath || '-'}`,
    `- วันที่ถาม: ${d.today || '-'}`,
  ];
  if (isDaily && d.todayColor) {
    lines.push(`- สีเสื้อมงคลของวันนี้: ${d.todayColor}${d.todayColorMeaning ? ` (${d.todayColorMeaning})` : ''}`);
  }
  lines.push(
    `- ประเภทคำถาม: ${isDaily
      ? 'ดวงรายวัน (เน้นช่วงวันนี้)'
      : 'ดวงรายเดือน (เน้นภาพรวมทั้งเดือน แบ่งเป็นช่วงต้น/กลาง/ปลายเดือน)'}`
  );
  lines.push('', `คำถาม: ${String(d.question || '').slice(0, 300)}`);
  return lines.join('\n');
}

module.exports = { SYSTEM_PROMPT, buildUserPrompt };
